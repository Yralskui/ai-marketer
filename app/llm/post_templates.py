def _find_product(topic: str) -> str | None:
    low = topic.lower()
    for product in SALAVATSTEKLO_PRODUCTS:
        if product.lower().replace("°", "") in low.replace("°", ""):
            return product
    for alias, product in _PRODUCT_ALIASES.items():
        if alias in low:
            # Серию уточняем по продолжению темы: «multicomfort light blue» → полное имя
            for full in SALAVATSTEKLO_PRODUCTS:
                rest = full.split(maxsplit=1)[1].lower() if " " in full else ""
                if full.startswith(product.rstrip("°")) and rest and rest.split()[0] in low:
                    return full
            return product
    return None


def _pick(
    templates: tuple[Template, ...], topic: str, fallback: Template | None
) -> Template | None:
    low = topic.lower().replace("ё", "е")
    scored = [(sum(k.replace("ё", "е") in low for k in t.keywords), t) for t in templates]
    best = max(score for score, _ in scored)
    if not best:
        return fallback
    candidates = [t for score, t in scored if score == best]
    # Одинаковые темы дают один и тот же шаблон, разные — разные
    return candidates[int(sha256(topic.encode()).hexdigest(), 16) % len(candidates)]


def _occasion(topic: str) -> Template | None:
    """Шаблон повода (день рождения завода, праздник) — только при явном совпадении."""
    low = topic.lower().replace("ё", "е")
    best, found = 0, None
    for template in OCCASION_TEMPLATES:
        score = sum(k.replace("ё", "е") in low for k in template.keywords)
        if score > best:
            best, found = score, template
    # «день строителя»/«новый год» узнаются по одному слову, дни рождения — по двум
    single = (
        found is not None
        and len(found.keywords) == 3
        and found.keywords[0].startswith(("день строител", "новый год"))
    )
    return found if best >= 2 or (best == 1 and single) else None


def _tag(value: str) -> str:
    words = re.findall(r"[\wа-яА-ЯёЁ]+", value)
    return (words[0].lower() if words else "новости")[:30]


def render_post(topic: str, business: str) -> str:
    """Готовый пост по теме: шаблон бренда для САЛАВАТСТЕКЛО или нейтральный для остальных."""
    topic = topic.strip().rstrip(".!") or "новости компании"
    salavat = "салаватстекл" in business.lower()
    if salavat:
        product = _find_product(topic)
        occasion = _occasion(topic)
        if occasion is not None:
            template = occasion
        elif product:
            template = PRODUCT_TEMPLATE
        else:
            template = _pick(SALAVATSTEKLO, topic, SALAVATSTEKLO_DEFAULT)
    else:
        product = None
        template = _pick(GENERIC, topic, GENERIC_DEFAULT)
    return template.text.format(
        topic=topic,
        Topic=topic[:1].upper() + topic[1:],
        business=business,
        product=product or "",
        tag=_tag(business),
    )


